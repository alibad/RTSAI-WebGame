import assert from 'node:assert/strict';
import { build } from '../web/node_modules/esbuild/lib/main.js';
const r = await build({ entryPoints: ['web/src/editor-pointer.ts'], bundle: true, format: 'esm', write: false });
const { EditorPointerStream } = await import('data:text/javascript;base64,' + Buffer.from(r.outputFiles[0].text).toString('base64'));
let release;
const gate = new Promise(resolve => { release = resolve; }), sent = [], failures = [];
const stream = new EditorPointerStream(async input => { sent.push(input); if (sent.length === 1) await gate; }, error => failures.push(error));
const input = (event, x, button = 1, mods = 0) => ({ event, x, y: 100, button, mods });
stream.push(input('down', 1));
stream.push(input('move', 2)); stream.push(input('move', 3)); stream.push(input('move', 4, 1, 4));
stream.push(input('up', 4)); stream.push(input('move', 5, 0));
release(); await new Promise(resolve => setTimeout(resolve, 0));
assert.deepEqual(sent.map(p => [p.event, p.x, p.button, p.mods]), [['down',1,1,0],['move',3,1,0],['move',4,1,4],['up',4,1,0],['move',5,0,0]], 'Delayed moves retain their buttons/modifiers and finish before release');
assert.deepEqual(failures, []);
let unlock;
const sentAfterReset = [], held = new Promise(resolve => { unlock = resolve; });
const reset = new EditorPointerStream(async p => { sentAfterReset.push(p); await held; }, error => failures.push(error));
reset.push(input('down', 10)); reset.push(input('move', 11)); reset.reset(); unlock();
await new Promise(resolve => setTimeout(resolve, 0));
assert.equal(sentAfterReset.length, 1, 'Closing a map discards queued input');
console.log('Editor pointer ordering, stroke edges, captured buttons, modifier changes, hover and reset passed.');
