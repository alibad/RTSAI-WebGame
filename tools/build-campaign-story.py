"""Build original campaign introductions locally from project map art and cached Kokoro.
Run with the neural-TTS Python environment; --text-only synchronizes the story without rendering.
No network calls, legacy movie clips, system voices, or hosted services.
"""
import os, json, pathlib, argparse, re, subprocess, shutil, hashlib, textwrap
ROOT = pathlib.Path(__file__).resolve().parents[1]
MOD = ROOT.parent / 'RTSAI-Mod'
args = argparse.ArgumentParser(); args.add_argument('--text-only', action='store_true'); args.add_argument('--source', help='another story JSON (tests)'); opt = args.parse_args()
source = pathlib.Path(opt.source) if opt.source else MOD / 'resources/campaign-story.json'
story = json.loads(source.read_text(encoding='utf-8'))
# The whole file is carried over (prologue, arcs, chapters, cast, radio); web/src/campaign.ts types it, so a field the
# page does not know fails the type check. Catch the mistakes the type check cannot see here.
cast, problems = story.get('cast', {}), []
for mid, ch in story['chapters'].items():
    if ch.get('status', 'playable') not in ('playable', 'coming'): problems.append(f'{mid}: status {ch["status"]!r}')
    if ch.get('speaker') and ch['speaker'] not in cast: problems.append(f'{mid}: speaker {ch["speaker"]!r} is not in the cast')
for arc in story['arcs']:
    problems += [f'arc {arc["id"]}: no chapter {mid!r}' for mid in arc['missions'] if mid not in story['chapters']]
for mid, calls in story.get('radio', {}).items():
    if mid not in story['chapters']: problems.append(f'radio {mid}: no such chapter')
    for call in calls:
        when = call.get('when')
        if not (when in ('start', 'victory', 'defeat') or (isinstance(when, dict) and len(when) == 1 and (isinstance(when.get('time', when.get('objective')), (int, float)) or isinstance(when.get('event'), str)))):
            problems.append(f'radio {mid}: when {when!r}')
        if call.get('speaker') not in cast: problems.append(f'radio {mid}: speaker {call.get("speaker")!r} is not in the cast')
if problems: raise SystemExit('campaign-story.json:\n  ' + '\n  '.join(problems))
(ROOT / 'web/src/campaign-story.ts').write_text('// Generated by tools/build-campaign-story.py from RTSAI-Mod/resources/campaign-story.json.\nimport type { CampaignStory } from "./campaign";\nconst story: CampaignStory = ' + json.dumps(story, ensure_ascii=False, indent=2) + ';\nexport default story;\n', encoding='utf-8', newline='\n')
if opt.text_only:
    print('Canonical story synchronized.'); raise SystemExit(0)
os.environ['HF_HUB_OFFLINE'] = '1'; os.environ['TRANSFORMERS_OFFLINE'] = '1'
os.environ.setdefault('HF_HOME', 'D:/AI Models/huggingface')
import numpy as np, soundfile as sf, torch
from kokoro import KModel, KPipeline
from PIL import Image, ImageDraw, ImageFont
cache = pathlib.Path(os.environ['HF_HOME']) / 'hub/models--hexgrad--Kokoro-82M/snapshots'
snapshot = next(p for p in cache.iterdir() if (p / 'kokoro-v1_0.pth').exists())
device = 'cuda' if torch.cuda.is_available() else 'cpu'; torch.set_num_threads(4)
print('Loading cached Kokoro am_michael on', device, flush=True)
model = KModel(repo_id='hexgrad/Kokoro-82M', config=str(snapshot/'config.json'), model=str(snapshot/'kokoro-v1_0.pth')).to(device).eval()
pipe = KPipeline(lang_code='a', repo_id='hexgrad/Kokoro-82M', model=model)
voice = torch.load(snapshot/'voices/am_michael.pt', weights_only=True)
out = ROOT / 'web/public/campaign-video'; out.mkdir(parents=True, exist_ok=True)
work = ROOT / 'artifacts/campaign-story'; work.mkdir(parents=True, exist_ok=True)
ffmpeg = shutil.which('ffmpeg'); probe = shutil.which('ffprobe'); assert ffmpeg and probe
font = lambda size: ImageFont.truetype('C:/Windows/Fonts/segoeui.ttf', size)
def timecode(t):
    ms = round(t*1000); h, ms = divmod(ms,3600000); m, ms = divmod(ms,60000); s, ms = divmod(ms,1000)
    return f'{h:02}:{m:02}:{s:02}.{ms:03}'
manifest = []
for mid, ch in story['chapters'].items():
    parts=[]; cues=[]; offset=0
    mapfile = MOD / 'mods/rtsai/campaigns/maps' / mid / 'map.png'
    if ch.get('status') == 'coming' or not mapfile.exists(): continue # no map yet: nothing to narrate over
    mapart = Image.open(mapfile).convert('RGB'); mapart.thumbnail((450,350))
    sentences = re.split(r'(?<=[.!?])\s+', ch['intro'])
    for i, sentence in enumerate(sentences):
        stem = work / f'{mid}-{i+1}'; wav = stem.with_suffix('.wav')
        audio = np.concatenate([r.audio.cpu().numpy() for r in pipe(sentence, voice=voice, speed=0.98)])
        assert len(audio)>1000 and np.isfinite(audio).all()
        sf.write(wav, np.concatenate([audio, np.zeros(9600,dtype=np.float32)]),24000)
        duration = sf.info(wav).duration
        image = Image.new('RGB',(960,540),(7,14,18)); draw=ImageDraw.Draw(image)
        for x in range(0,960,40): draw.line((x,0,x,540), fill=(16,30,34))
        for y in range(0,540,40): draw.line((0,y,960,y), fill=(16,30,34))
        draw.text((36,24),'RTS AI / LINES OF HOPE', font=font(16),fill=(174,154,105))
        draw.text((36,55),ch['title'],font=font(32),fill=(241,210,139))
        draw.text((36,100),ch['location'].upper(),font=font(16),fill=(139,185,185))
        image.paste(mapart,(36+(450-mapart.width)//2,155+(350-mapart.height)//2))
        draw.rectangle((35,154,487,506),outline=(91,130,129),width=2)
        draw.text((522,155),'COMMAND TRANSMISSION',font=font(15),fill=(139,185,185))
        draw.multiline_text((522,195),'\n'.join(textwrap.wrap(sentence,32)),font=font(22),fill=(224,231,224),spacing=10)
        draw.text((522,480),f'BRIEFING {i+1:02} / {len(sentences):02}',font=font(14),fill=(174,154,105))
        poster=stem.with_suffix('.png'); image.save(poster)
        segment=stem.with_suffix('.mp4')
        subprocess.run([ffmpeg,'-hide_banner','-loglevel','error','-y','-loop','1','-i',str(poster),'-i',str(wav),'-t',str(duration),'-r','24','-c:v','libx264','-preset','veryfast','-crf','24','-pix_fmt','yuv420p','-af','loudnorm=I=-16:TP=-1.5:LRA=11','-c:a','aac','-b:a','128k','-movflags','+faststart',str(segment)],check=True)
        cues.append(f'{timecode(offset)} --> {timecode(offset+duration)}\n{sentence}\n'); offset+=duration;parts.append(segment)
    concat = work / f'{mid}-concat.txt'; concat.write_text('\n'.join("file '"+p.as_posix()+"'" for p in parts),encoding='utf-8')
    target=out/f'{mid}.mp4'
    subprocess.run([ffmpeg,'-hide_banner','-loglevel','error','-y','-f','concat','-safe','0','-i',str(concat),'-c','copy','-movflags','+faststart',str(target)],check=True)
    (out/f'{mid}.vtt').write_text('WEBVTT\n\n'+'\n'.join(cues),encoding='utf-8')
    duration=float(subprocess.check_output([probe,'-v','error','-show_entries','format=duration','-of','csv=p=0',str(target)]))
    manifest.append({'id':mid,'seconds':duration,'bytes':target.stat().st_size,'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'mapSource':str(mapfile.relative_to(MOD))})
    print(mid,round(duration,1),'seconds',flush=True)
(out/'manifest.json').write_text(json.dumps({'title':story['title'],'source':'RTSAI-Mod/resources/campaign-story.json','provenance':story['provenance'],'narration':{'engine':'Kokoro-82M','voice':'am_michael','device':device,'speed':0.98,'loudness':'-16 LUFS / -1.5 dBTP'},'videos':manifest},indent=2),encoding='utf-8')
print(len(manifest),'campaign introductions rendered.',flush=True)
