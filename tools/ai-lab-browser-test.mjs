import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from '../web/node_modules/playwright-core/index.mjs';
const out = 'artifacts/ai-lab'; fs.mkdirSync(out, { recursive: true });
const exe = path.join(process.env.LOCALAPPDATA, 'ms-playwright/chromium-1228/chrome-win64/chrome.exe');
const browser = await chromium.launch({ executablePath: exe, headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errors = []; page.on('pageerror', e => { errors.push(String(e)); console.log(e.stack); });
page.on('requestfailed', r => console.log('failed request', r.url(), r.failure()));
const results = {};
const progress = setInterval(() => page.evaluate(() => { const s = window.store?.getState(); return s ? { phase: s.phase, stage: s.stage, error: s.error, tick: s.ui?.tick } : {}; }).then(s => console.log('progress', s)).catch(() => {}), 30000);
const ready = async () => { await page.waitForFunction(() => ['playing', 'error'].includes(window.store.getState().phase), null, { timeout: 180000 }); assert.equal(await page.evaluate(() => window.store.getState().phase), 'playing'); };
try {
  await page.goto(`http://127.0.0.1:3490/?profile=public&mode=practice&runtime=${process.env.TEST_RUNTIME ?? 'aot'}`);
  await page.waitForFunction(() => window.store?.getState().phase === 'error' || document.querySelector('[data-practice] select[aria-label="Your unit"] option'), null, { timeout: 600000 });
  assert.notEqual(await page.evaluate(() => window.store.getState().phase), 'error');
  console.log('Workshop catalog loaded');
  await page.getByLabel('Scenario request').fill('Survive with 6 infantry against 8 units for 30 seconds');
  await page.getByRole('button', { name: 'Interpret request', exact: true }).click();
  assert.equal(await page.getByLabel('Your force').inputValue(), '6');
  assert.equal(await page.getByLabel('Opponent force').inputValue(), '8');
  assert.equal(await page.getByLabel('Duration seconds').inputValue(), '30');
  await page.getByLabel('Your unit').selectOption('r2cnrifle');
  await page.getByLabel('Opponent unit').selectOption('r2cnrifle');
  await page.getByLabel('Opponent orders').selectOption('hold');
  await page.getByLabel('Your force').fill('99');
  await page.getByRole('button', { name: 'Preview & validate routes', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '1–24' }).waitFor();
  assert(await page.getByRole('button', { name: 'Launch practice', exact: true }).isDisabled());
  await page.getByLabel('Your force').fill('6');
  await page.getByRole('button', { name: 'Preview & validate routes', exact: true }).click();
  await page.getByText('Both forces and ground routes validated', { exact: false }).waitFor({ timeout: 180000 });
  await page.waitForFunction(() => window.game.client.cur?.actors.length >= 14, null, { timeout: 30000 });
  await page.screenshot({ path: `${out}/workshop.png` });
  await page.setViewportSize({ width: 844, height: 390 });
  const workshopBounds = await page.locator('[data-practice]').boundingBox(); assert(workshopBounds && workshopBounds.y >= 0 && workshopBounds.y + workshopBounds.height <= 390);
  await page.getByRole('button', { name: 'Launch practice', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${out}/workshop-compact.png` });
  await page.setViewportSize({ width: 1600, height: 900 });
  await page.getByRole('button', { name: 'Launch practice', exact: true }).click(); await ready();
  await page.evaluate(() => window.game.client.send({ type: 'speed', speed: 8 }));
  await page.waitForFunction(() => window.game.coach.lab?.status === 'complete', null, { timeout: 120000 });
  results.practice = await page.evaluate(() => ({ scenario: JSON.parse(window.game.scenarioJson), lab: window.game.coach.lab, frames: window.game.coach.frames.length }));
  assert.equal(results.practice.scenario.seed, 42); assert.equal(results.practice.lab.objective, 'survive');
  assert.equal(results.practice.lab.metrics.sides[0].alive, 6);
  assert.equal(await page.evaluate(() => window.game.coach.frames.at(-1).army), 6);
  if (!(await page.locator('[data-coach]').isVisible())) await page.getByRole('button', { name: /^Battlefield review/ }).click();
  await page.getByRole('button', { name: 'Repeat same seed & forces', exact: true }).click(); await ready();
  await page.evaluate(() => window.game.client.send({ type: 'speed', speed: 8 }));
  await page.waitForFunction(() => window.game.coach.lab?.status === 'complete' && !!window.game.coach.previousPractice, null, { timeout: 120000 });
  results.repeat = await page.evaluate(() => ({ previous: window.game.coach.previousPractice, current: window.game.coach.lab.metrics }));
  assert.equal(results.repeat.previous.sides[0].alive, results.repeat.current.sides[0].alive);
  assert.equal(results.repeat.current.elapsed, 30);
  await page.getByLabel('Review timeline').fill('100');
  await page.waitForFunction(() => !!window.game.coach.review);
  const blocked = await page.evaluate(async () => (await window.game.command({ cmd: 'stop' })).error === 'Return live before issuing orders.'); assert(blocked);
  await page.screenshot({ path: `${out}/coaching.png` });
  await page.getByRole('button', { name: 'Return live', exact: true }).click();
  assert.equal(await page.evaluate(() => window.game.coach.review), null);
  console.log('Practice objective and safe replay seek passed');
  // Real native doctrine orders in the arena; retain recording for parity.
  const scenario = { map: 'web-arena', seed: 42, sandbox: true, players: [{ slot: 'Multi0', faction: 'saudi' }, { slot: 'Multi1', faction: 'iran', bot: 'webidle', doctrine: 'adaptive' }], options: { fog: 'False', explored: 'True', shortgame: 'False', crates: 'False' }, placements: Array.from({ length: 8 }, (_, i) => ({ id: 'r2cnrifle', side: i < 6 ? 0 : 1, u: i < 6 ? 48 + i : 76 + i - 6, v: 60, order: 'hold' })) };
  await page.evaluate(s => window.game.start(JSON.stringify(s)), scenario); await ready();
  await page.waitForFunction(() => window.game.coach.lab?.doctrines[0]?.decisions.length > 0, null, { timeout: 60000 });
  results.doctrine = await page.evaluate(() => window.game.coach.lab.doctrines[0]);
  assert.equal(results.doctrine.decisions[0].mode, 'regroup');
  await page.evaluate(() => window.game.requestVerify());
  await page.waitForFunction(() => window.store.getState().verify && !/\.\.\.$|…$/.test(window.store.getState().verify), null, { timeout: 300000 });
  results.verify = await page.evaluate(() => window.store.getState().verify); assert.match(results.verify, /identical/i);
  console.log('Doctrine native parity', results.verify);
  await page.screenshot({ path: `${out}/personality.png` });
  // Proposal annotations use actual companion-held commands, never synthetic orders.
  await page.evaluate(() => { window.game.cc.setMode('mock'); window.game.cc.setEnabled(true); });
  await page.evaluate(s => window.game.start(s), fs.readFileSync('scenarios/skirmish-public.json', 'utf8')); await ready();
  await page.waitForFunction(() => window.store.getState().cc.strategies?.available, null, { timeout: 60000 });
  await page.evaluate(async () => { window.game.cc.setOfferSteps(false); await window.game.cc.selectStrategy('economy', 500); await window.game.cc.strategyStep(false); });
  await page.locator('[data-annotations]').waitFor({ timeout: 30000 });
  await page.waitForFunction(() => {
    const p = window.game.cc.pending();
    return p?.commands?.length && document.querySelector('[data-annotations]')?.getAttribute('data-proposal-id') === p.proposalId;
  }, null, { timeout: 30000 });
  results.annotationCommands = await page.evaluate(() => window.game.cc.pending().commands);
  const aligned = await page.evaluate(() => {
    const g = window.game, command = g.cc.pending().commands[0], actor = g.client.cur.actorById.get(command.actor_id), box = g.canvas.getBoundingClientRect(), scale = g.canvas.width / box.width;
    const circle = document.querySelector('[data-annotations] circle');
    return Math.abs(Number(circle.getAttribute('cx')) - (box.width / 2 + (actor.sx - g.cam.x) * g.cam.zoom / scale)) < 2 && Math.abs(Number(circle.getAttribute('cy')) - (box.height / 2 + (actor.sy - g.cam.y) * g.cam.zoom / scale)) < 2;
  }); assert(aligned, 'Proposal ring must align with the actor’s native screen position');
  const tick = await page.evaluate(() => window.store.getState().ui.tick);
  await page.screenshot({ path: `${out}/annotations.png` });
  await page.getByRole('button', { name: 'Dismiss preview', exact: true }).click();
  assert.equal(await page.locator('[data-annotations]').count(), 0);
  assert.equal(await page.evaluate(() => window.game.cc.pending().state), 'pending');
  results.dismissedAtTick = tick;
  await page.evaluate(() => window.game.quit());
  await page.getByRole('button', { name: /^Skirmish/ }).first().click();
  await page.getByLabel('Opponent 1 personality').selectOption('adaptive');
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('rtsai.opponents'))[0].doctrine), 'adaptive');
  await page.screenshot({ path: `${out}/personality-setup.png` });
  assert.deepEqual(errors, []); results.errors = errors; results.passed = true;
  fs.writeFileSync(`${out}/browser-results.json`, JSON.stringify(results, null, 2));
  console.log('All four feature flows passed');
} catch(e) { await page.screenshot({ path: `${out}/failure.png` }); fs.writeFileSync(`${out}/failure.json`, JSON.stringify({ error: String(e), errors, results }, null, 2)); throw e; } finally { clearInterval(progress); await browser.close(); }
